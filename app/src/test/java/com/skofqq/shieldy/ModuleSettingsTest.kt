package com.skofqq.shieldy

import com.skofqq.shieldy.data.ModuleSettings
import com.skofqq.shieldy.root.RootShell
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class ModuleSettingsTest {

    @Test
    fun `the allow-list holds exactly the documented keys`() {
        assertEquals(
            setOf(
                "redirect_ipv4",
                "redirect_ipv6",
                "tether_redirect",
                "disable_private_dns",
                "mirror_config",
                "restart_delay_max",
                "run_gid",
                "autostart",
            ),
            ModuleSettings.SPECS.keys,
        )
    }

    @Test
    fun `run_gid accepts a group name, a numeric gid or nothing at all`() {
        assertEquals("", ModuleSettings.validate("run_gid", "").getOrThrow().second)
        assertEquals("", ModuleSettings.validate("run_gid", "   ").getOrThrow().second)
        assertEquals("net_admin", ModuleSettings.validate("run_gid", "net_admin").getOrThrow().second)
        assertEquals("3005", ModuleSettings.validate("run_gid", "3005").getOrThrow().second)
    }

    @Test
    fun `run_gid rejects anything that could carry a command`() {
        assertTrue(ModuleSettings.validate("run_gid", "net admin").isFailure)
        assertTrue(ModuleSettings.validate("run_gid", "; rm -rf /").isFailure)
        assertTrue(ModuleSettings.validate("run_gid", "net_admin; reboot").isFailure)
        assertTrue(ModuleSettings.validate("run_gid", "3005 4000").isFailure)
        assertTrue(ModuleSettings.validate("run_gid", "-1").isFailure)
    }

    @Test
    fun `unknown keys are rejected`() {
        assertTrue(ModuleSettings.validate("rm_rf", "true").isFailure)
        assertTrue(ModuleSettings.validate("", "true").isFailure)
        assertTrue(ModuleSettings.validate("redirect_ipv4; reboot", "true").isFailure)
    }

    @Test
    fun `boolean values are normalised`() {
        assertEquals("redirect_ipv4" to "true", ModuleSettings.validate("redirect_ipv4", "TRUE").getOrThrow())
        assertEquals("false", ModuleSettings.validate("mirror_config", "0").getOrThrow().second)
        assertTrue(ModuleSettings.validate("redirect_ipv4", "maybe").isFailure)
        assertTrue(ModuleSettings.validate("redirect_ipv4", "true; rm -rf /").isFailure)
    }

    @Test
    fun `redirect_ipv6 only accepts the three modes`() {
        assertEquals("auto", ModuleSettings.validate("redirect_ipv6", "auto").getOrThrow().second)
        assertEquals("redirect", ModuleSettings.validate("redirect_ipv6", "REDIRECT").getOrThrow().second)
        assertEquals("off", ModuleSettings.validate("redirect_ipv6", "off").getOrThrow().second)
        assertTrue(ModuleSettings.validate("redirect_ipv6", "true").isFailure)
    }

    @Test
    fun `restart_delay_max is clamped to the documented range`() {
        assertEquals("5", ModuleSettings.validate("restart_delay_max", "5").getOrThrow().second)
        assertEquals("600", ModuleSettings.validate("restart_delay_max", "600").getOrThrow().second)
        assertTrue(ModuleSettings.validate("restart_delay_max", "4").isFailure)
        assertTrue(ModuleSettings.validate("restart_delay_max", "601").isFailure)
        assertTrue(ModuleSettings.validate("restart_delay_max", "60s").isFailure)
    }

    @Test
    fun `module conf is parsed and foreign keys dropped`() {
        val conf = """
            # generated by the module
            redirect_ipv4=true
            redirect_ipv6 = auto
            tether_redirect=false   # off by default
            disable_private_dns="true"
            mirror_config=1
            restart_delay_max=120
            some_other_key=whatever
        """.trimIndent()

        val parsed = ModuleSettings.parseConf(conf)

        assertEquals("true", parsed["redirect_ipv4"])
        assertEquals("auto", parsed["redirect_ipv6"])
        assertEquals("false", parsed["tether_redirect"])
        assertEquals("true", parsed["disable_private_dns"])
        assertEquals("true", parsed["mirror_config"])
        assertEquals("120", parsed["restart_delay_max"])
        assertNull(parsed["some_other_key"])
        assertFalse(parsed.containsKey("some_other_key"))
    }

    @Test
    fun `shell quoting neutralises quotes and metacharacters`() {
        assertEquals("'plain'", RootShell.quote("plain"))
        assertEquals("'a b'", RootShell.quote("a b"))
        assertEquals("""'it'\''s'""", RootShell.quote("it's"))
        assertEquals("""'; rm -rf /'""", RootShell.quote("; rm -rf /"))
    }
}
